def show_message(text: str, failed: bool) -> None:
    """Frozen windowed builds have no console; surface CLI results in a message box."""
    if os.name != "nt":
        return
    try:
        import ctypes
        flags = 0x10 if failed else 0x40
        ctypes.windll.user32.MessageBoxW(None, text[:2000], APP_TITLE, flags)
    except Exception:
        pass


def console_available() -> bool:
    """A windowed EXE has no console; a redirected console still counts."""
    stream = sys.stdout
    if stream is None:
        return False
    try:
        stream.write("")
        stream.flush()
        return True
    except (OSError, ValueError, AttributeError):
        return False


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)
    if args == ["--gui-self-test"]:
        return gui_self_test()
    if not args or args == ["--gui"]:
        return run_gui()
    if not console_available():
        output = io.StringIO()
        with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
            code = main_cli(args)
        show_message(output.getvalue().strip() or f"Exited with code {code}.", bool(code))
        return code
    return main_cli(args)


