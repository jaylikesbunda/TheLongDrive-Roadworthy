class InstallerError(Exception):
    pass


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest().upper()


def read_json(path: Path) -> dict:
    try:
        return json.loads(path.read_text(encoding="utf-8-sig"))
    except (OSError, ValueError) as exc:
        raise InstallerError(f"Cannot read installation receipt: {path}") from exc


def write_json(path: Path, data: dict) -> None:
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    os.replace(temporary, path)


def valid_hash(value) -> bool:
    return isinstance(value, str) and len(value) == 64 and all(c in "0123456789ABCDEF" for c in value)


def receipt_hash(receipt: dict, key: str) -> str:
    value = receipt.get(key)
    return value.upper() if isinstance(value, str) else ""


def parse_vdf(text: str) -> dict:
    """Parse quoted Steam KeyValues, including braces and escaped Windows paths."""
    token_re = re.compile(r'\s+|//[^\r\n]*|"(?:\\.|[^"\\])*"|[{}]')
    tokens = []
    position = 0
    while position < len(text):
        match = token_re.match(text, position)
        if not match:
            raise InstallerError("Malformed Steam library manifest.")
        token = match.group(0)
        position = match.end()
        if token.isspace() or token.startswith("//"):
            continue
        if token.startswith('"'):
            token = re.sub(r'\\(["\\])', lambda m: m.group(1), token[1:-1])
            tokens.append(("value", token))
        else:
            tokens.append((token, token))
    index = 0

    def section(nested=False):
        nonlocal index
        result = {}
        while index < len(tokens):
            kind, key = tokens[index]
            index += 1
            if kind == "}":
                if not nested:
                    raise InstallerError("Unbalanced Steam manifest.")
                return result
            if kind != "value" or index >= len(tokens):
                raise InstallerError("Malformed Steam manifest entry.")
            kind, value = tokens[index]
            index += 1
            if kind == "{":
                result[key] = section(True)
            elif kind == "value":
                result[key] = value
            else:
                raise InstallerError("Malformed Steam manifest value.")
        if nested:
            raise InstallerError("Unclosed Steam manifest section.")
        return result

    return section()


def steam_roots() -> list[Path]:
    candidates = []
    if os.name == "nt":
        import winreg
        for hive, key, value in (
            (winreg.HKEY_CURRENT_USER, r"Software\Valve\Steam", "SteamPath"),
            (winreg.HKEY_LOCAL_MACHINE, r"Software\Valve\Steam", "InstallPath"),
        ):
            for view in (0, winreg.KEY_WOW64_32KEY, winreg.KEY_WOW64_64KEY):
                try:
                    with winreg.OpenKey(hive, key, 0, winreg.KEY_READ | view) as handle:
                        candidates.append(Path(winreg.QueryValueEx(handle, value)[0]))
                except OSError:
                    pass
    for name in ("ProgramFiles(x86)", "ProgramFiles"):
        if os.environ.get(name):
            candidates.append(Path(os.environ[name]) / "Steam")
    return unique_paths(candidates)


def unique_paths(paths) -> list[Path]:
    found = {}
    for path in paths:
        path = Path(path).expanduser().resolve()
        found.setdefault(str(path).casefold(), path)
    return list(found.values())


def discover_games(roots=None) -> list[Path]:
    libraries = []
    for steam in steam_roots() if roots is None else roots:
        steam = Path(steam)
        libraries.append(steam)
        manifest = steam / "steamapps" / "libraryfolders.vdf"
        if not manifest.is_file():
            continue
        try:
            entries = parse_vdf(manifest.read_text(encoding="utf-8-sig"))["libraryfolders"]
            for key, entry in entries.items():
                if isinstance(entry, dict) and isinstance(entry.get("path"), str):
                    libraries.append(Path(entry["path"]))
                elif key.isdigit() and isinstance(entry, str):
                    libraries.append(Path(entry))
        except (OSError, KeyError, InstallerError):
            continue
    games = []
    for library in unique_paths(libraries):
        manifest = library / "steamapps" / f"appmanifest_{APP_ID}.acf"
        try:
            data = parse_vdf(manifest.read_text(encoding="utf-8-sig"))["AppState"]
            if data.get("appid") != APP_ID:
                continue
            common = (library / "steamapps" / "common").resolve()
            game = (common / data["installdir"]).resolve()
            if not game.is_relative_to(common):
                continue
            if valid_game(game):
                games.append(game)
        except (OSError, KeyError, TypeError, InstallerError):
            continue
    return unique_paths(games)


def valid_game(game: Path) -> bool:
    return (game / "TheLongDrive.exe").is_file() and game_assembly(game).is_file()


def game_assembly(game: Path) -> Path:
    return game / "TheLongDrive_Data" / "Managed" / "Assembly-CSharp.dll"


def managed_dir(game: Path) -> Path:
    return game_assembly(game).parent


def verified_v3(game: Path) -> dict:
    """The multiplayer receipt, validated together with the installed helper."""
    managed = managed_dir(game)
    receipt = read_json(managed / "tldmp-v3-receipt.json")
    if receipt.get("version") != 3:
        raise InstallerError("tldmp-v3-receipt.json is not a multiplayer v3 receipt.")
    if receipt_hash(receipt, "originalSha256") != ORIGINAL_SHA256:
        raise InstallerError("The multiplayer receipt does not describe the supported original build.")
    if not valid_hash(receipt_hash(receipt, "patchedSha256")) or not valid_hash(receipt_hash(receipt, "runtimeSha256")):
        raise InstallerError("The multiplayer receipt is missing its verified hashes.")
    helper = managed / "Tld.Multiplayer.dll"
    if not helper.is_file() or sha256(helper) != receipt_hash(receipt, "runtimeSha256"):
        raise InstallerError("The installed multiplayer helper is missing or changed. Restore and reinstall the multiplayer patch.")
    return receipt


def installed_state(game: Path) -> str:
    managed = managed_dir(game)
    current = sha256(game_assembly(game))
    if current == ORIGINAL_SHA256:
        return "original"
    v4_path = managed / V4_RECEIPT
    if v4_path.is_file():
        receipt = read_json(v4_path)
        patched = receipt_hash(receipt, "patchedSha256")
        original = receipt_hash(receipt, "originalSha256")
        if receipt.get("version") != 4 or not valid_hash(patched) or not valid_hash(original):
            raise InstallerError("tldmp-v4-receipt.json is not a recognised single-player receipt.")
        v3 = verified_v3(game)
        if receipt_hash(v3, "patchedSha256") != original or receipt_hash(v3, "runtimeSha256") != receipt_hash(receipt, "runtimeSha256"):
            raise InstallerError("The single-player receipt does not match the installed multiplayer build.")
        if current == patched:
            backup = managed / V4_BACKUP
            if not backup.is_file() or sha256(backup) != original:
                raise InstallerError("The single-player backup is missing or changed. Refusing to touch an unknown installation.")
            return "v4"
        if current == original:
            # An interrupted restore already put the multiplayer assembly back.
            return "v3"
        raise InstallerError("tldmp-v4-receipt.json does not match the installed assembly.")
    for version in (3, 1):
        receipt_path = managed / f"tldmp-v{version}-receipt.json"
        if not receipt_path.is_file():
            continue
        receipt = read_json(receipt_path)
        if receipt.get("patchedSha256", "").upper() != current:
            continue
        backup = managed / f"Assembly-CSharp.tldmp-v{version}-original.bin"
        if receipt.get("originalSha256") != ORIGINAL_SHA256 or not backup.is_file() or sha256(backup) != ORIGINAL_SHA256:
            raise InstallerError("The original backup is missing or changed. Game files were not modified.")
        if version == 3:
            helper = managed / "Tld.Multiplayer.dll"
            if not helper.is_file() or sha256(helper) != receipt.get("runtimeSha256", "").upper():
                raise InstallerError("The installed helper is missing or changed. Refusing to overwrite an unknown installation.")
        return f"v{version}"
    raise InstallerError(
        "Unsupported or modified game build. This patch supports 2024.11.26b_test only. "
        "It will not overwrite another mod or switch your Steam beta branch."
    )


def _version_tuple(value) -> tuple | None:
    """Strict numeric X.Y.Z only; anything else is an unknown version."""
    if not isinstance(value, str):
        return None
    parts = value.split(".")
    if len(parts) != 3 or any(not re.fullmatch(r"[0-9]+", part) for part in parts):
        return None
    return tuple(int(part) for part in parts)


def installation_info(game: Path) -> dict:
    """Recognised state plus release/build metadata and its relation to this
    installer. Always runs the full installed_state integrity chain first;
    missing or malformed metadata only downgrades the reported version, never
    the validation."""
    managed = managed_dir(game)
    state = installed_state(game)
    info = {"state": state, "version": None, "build": None, "relation": "original"}
    if state == "original":
        return info
    receipt = None
    if state in ("v3", "v4"):
        receipt = read_json(managed / "tldmp-v3-receipt.json")
    elif state == "v1":
        legacy = managed / "tldmp-v1-receipt.json"
        receipt = read_json(legacy) if legacy.is_file() else None
    if isinstance(receipt, dict):
        if _version_tuple(receipt.get("roadworthyVersion")) is not None:
            info["version"] = receipt["roadworthyVersion"]
        build = receipt.get("installerPayloadSha256")
        info["build"] = build.upper() if isinstance(build, str) and valid_hash(build) else None
        if isinstance(receipt.get("sourceSignature"), str):
            info["sourceSignature"] = receipt["sourceSignature"]
    installed = _version_tuple(info["version"])
    bundled = _version_tuple(VERSION)
    if installed is not None and bundled is not None and installed > bundled:
        info["relation"] = "newer"
    elif state == "v4" and info["build"] == PAYLOAD_SHA256:
        info["relation"] = "current"
    elif state == "v1":
        info["relation"] = "legacy"
    else:
        info["relation"] = "update"
    return info


UPDATES_API = "https://api.github.com/repos/jaylikesbunda/TheLongDrive-Roadworthy/releases?per_page=100&page={}"
RELEASE_PAGE = "https://github.com/jaylikesbunda/TheLongDrive-Roadworthy/releases/tag/"


def check_updates() -> dict:
    """Best published release on GitHub, prereleases included, drafts skipped.
    Strictly read-only: unauthenticated GET, 5s timeout, 2 MiB cap, at most the
    first three generated pages, no server-provided URLs followed. Any failure
    raises InstallerError; a missing published release reports version None."""
    bundled = _version_tuple(VERSION)
    best, best_tag = None, None
    for page in (1, 2, 3):
        request = urllib.request.Request(UPDATES_API.format(page), headers={
            "Accept": "application/vnd.github+json",
            "User-Agent": f"Roadworthy-Installer/{VERSION}"})
        try:
            with urllib.request.urlopen(request, timeout=5) as response:
                data = response.read(2 * 1024 * 1024 + 1)
        except (OSError, ValueError) as exc:
            raise InstallerError(f"Could not check for newer releases: {exc}")
        if len(data) > 2 * 1024 * 1024:
            raise InstallerError("The release list response was too large; refusing it.")
        try:
            releases = json.loads(data)
        except ValueError:
            raise InstallerError("The release list was not valid JSON.")
        if not isinstance(releases, list):
            raise InstallerError("The release list had an unexpected shape.")
        for entry in releases:
            if not isinstance(entry, dict) or entry.get("draft") or not entry.get("published_at"):
                continue
            tag = entry.get("tag_name")
            if not isinstance(tag, str):
                continue
            candidate = _version_tuple(tag[1:] if tag.lower().startswith("v") else tag)
            if candidate is not None and (best is None or candidate > best):
                best, best_tag = candidate, tag
        if len(releases) < 100:
            break
    if best is None:
        return {"version": None, "tag": None, "newer": False, "url": None}
    newer = bundled is not None and best > bundled
    return {"version": ".".join(str(part) for part in best), "tag": best_tag, "newer": newer,
            "url": RELEASE_PAGE + urllib.parse.quote(best_tag, safe="")}


def stamp_metadata(receipt_path: Path) -> None:
    """Record this installer's release/build identity on a receipt we own,
    preserving every existing field."""
    receipt = read_json(receipt_path)
    receipt["roadworthyVersion"] = VERSION
    receipt["installerPayloadSha256"] = PAYLOAD_SHA256
    write_json(receipt_path, receipt)


def choose_game(explicit: str | None) -> Path:
    if explicit:
        game = Path(explicit).expanduser().resolve()
        if not valid_game(game):
            raise InstallerError(f"Not a The Long Drive installation: {game}")
        return game
    games = discover_games()
    if not games:
        raise InstallerError('Steam game not found. Run with --game-dir "FULL PATH TO THE GAME".')
    supported = []
    for game in games:
        try:
            installed_state(game)
            supported.append(game)
        except InstallerError:
            pass
    choices = supported or games
    if len(choices) != 1:
        lines = "\n".join(f"  {game}" for game in choices)
        raise InstallerError(f'Multiple installations found. Use --game-dir to select one:\n{lines}')
    return choices[0]


def payload_bytes() -> bytes:
    data = base64.b64decode(PAYLOAD_B64, validate=True)
    if hashlib.sha256(data).hexdigest().upper() != PAYLOAD_SHA256:
        raise InstallerError("Embedded patch payload failed its integrity check.")
    return data


def extract_payload(destination: Path) -> None:
    destination = destination.resolve()
    destination.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(io.BytesIO(payload_bytes())) as archive:
        for entry in archive.infolist():
            relative = PurePosixPath(entry.filename)
            if relative.is_absolute() or ".." in relative.parts or "\\" in entry.filename or ":" in entry.filename:
                raise InstallerError("Unsafe embedded payload path.")
            if entry.is_dir():
                continue
            target = destination.joinpath(*relative.parts).resolve()
            if not target.is_relative_to(destination):
                raise InstallerError("Embedded payload path escaped the cache directory.")
            target.parent.mkdir(parents=True, exist_ok=True)
            data = archive.read(entry)
            if not target.is_file() or target.read_bytes() != data:
                temporary = target.with_name(target.name + ".installing")
                temporary.write_bytes(data)
                temporary.replace(target)
    if sha256(destination / ".tools" / "cecil.zip") != CECIL_SHA256:
        raise InstallerError("Bundled Mono.Cecil dependency failed its integrity check.")


@contextlib.contextmanager
def installer_lock(cache: Path):
    import msvcrt
    cache.mkdir(parents=True, exist_ok=True)
    with (cache / "installer.lock").open("a+b") as handle:
        if handle.seek(0, 2) == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        except OSError as exc:
            raise InstallerError("Another patch installer is already running. Close it first.") from exc
        try:
            yield
        finally:
            handle.seek(0)
            msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)


def powershell() -> Path:
    return Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "WindowsPowerShell" / "v1.0" / "powershell.exe"


def compiler() -> Path:
    return Path(os.environ.get("SystemRoot", r"C:\Windows")) / "Microsoft.NET" / "Framework64" / "v4.0.30319" / "csc.exe"


def system_environment() -> dict:
    environment = os.environ.copy()
    # Use Windows PowerShell's own modules, even when started from PowerShell 7.
    environment["PSModulePath"] = str(powershell().parent / "Modules") + ";" + str(Path(os.environ.get("ProgramFiles", r"C:\Program Files")) / "WindowsPowerShell" / "Modules")
    return environment


@contextlib.contextmanager
def system_dll_search():
    # PyInstaller adjusts DLL search paths for its bundled Python runtime.
    # System PowerShell/.NET children must use Windows DLLs instead of inheriting it.
    frozen = os.name == "nt" and getattr(sys, "frozen", False)
    if frozen:
        import ctypes
        set_directory = ctypes.windll.kernel32.SetDllDirectoryW
        set_directory.argtypes = [ctypes.c_wchar_p]
        set_directory.restype = ctypes.c_bool
        if not set_directory(None):
            raise OSError("Could not configure system DLL search paths.")
    try:
        yield
    finally:
        if frozen:
            set_directory(str(sys._MEIPASS))


def run_process(command, cwd: Path, log, label: str) -> None:
    """Run a helper with no console window and echo its output into the log."""
    with subprocess.Popen([str(item) for item in command], cwd=str(cwd), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, encoding="utf-8", errors="replace", creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0)) as process:
        assert process.stdout is not None
        for line in process.stdout:
            print(line, end="", flush=True)
            log.write(line)
            log.flush()
        if process.wait() != 0:
            raise InstallerError(f"{label} failed. Installation was stopped.")


def run_ps(work: Path, log, script: str, game: Path, *arguments: str) -> None:
    command = [str(powershell()), "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-File", str(work / script), "-GameDirectory", str(game), *arguments]
    with system_dll_search(), subprocess.Popen(command, cwd=work, env=system_environment(), stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          text=True, encoding="utf-8", errors="replace", creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0)) as process:
        assert process.stdout is not None
        for line in process.stdout:
            print(line, end="", flush=True)
            log.write(line)
            log.flush()
        if process.wait() != 0:
            raise InstallerError(f"{script} failed. See the log above; installation was stopped.")


def preflight(game: Path, need_compiler=True) -> None:
    if not powershell().is_file():
        raise InstallerError("Windows PowerShell is unavailable. This installer targets Windows 10/11 x64.")
    if need_compiler and not compiler().is_file():
        raise InstallerError("The built-in .NET Framework compiler is missing. Enable/repair Windows .NET Framework 4.x, then rerun.")
    # Block before a long build, rather than discovering the running game at install time.
    with system_dll_search():
        result = subprocess.run([str(powershell()), "-NoProfile", "-NonInteractive", "-Command",
                                 "if (Get-Process -Name TheLongDrive -ErrorAction SilentlyContinue) { exit 9 }"],
                                env=system_environment(), capture_output=True, creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    if result.returncode == 9:
        raise InstallerError("Close The Long Drive, then rerun this installer.")
    if result.returncode:
        raise InstallerError("Could not check whether the game is running.")


def stage_replace(source: Path, target: Path, expected: str, suffix: str) -> None:
    """Copy source next to target, verify it, then swap it in one step."""
    expected = expected.upper()
    temporary = target.with_name(target.name + suffix)
    try:
        shutil.copyfile(source, temporary)
        if sha256(temporary) != expected:
            raise InstallerError("Staged file failed its hash check. Nothing was replaced.")
        os.replace(temporary, target)
        if sha256(target) != expected:
            raise InstallerError("Installed file failed its hash check. Restore the original game through Steam.")
    finally:
        if temporary.exists():
            try:
                temporary.unlink()
            except OSError:
                pass


def ensure_singleplayer_tools(work: Path, log) -> Path:
    """Compile the v4 patcher/verifier from the bundled sources (payload option a)."""
    source_dir = work / "packaging" / "singleplayer"
    tools = work / ".tools" / "singleplayer"
    tools.mkdir(parents=True, exist_ok=True)
    cecil = tools / "Mono.Cecil.dll"
    helper = tools / "TldStableHelper.dll"
    patcher = tools / "PatchV4.exe"
    verifier = tools / "VerifyV4.exe"
    signature = hashlib.sha256("".join(
        name + ":" + hashlib.sha256((source_dir / name).read_bytes()).hexdigest() + "\n"
        for name in SINGLEPLAYER_SOURCES
    ).encode("ascii")).hexdigest().upper()
    marker = tools / "build.txt"
    if marker.is_file() and marker.read_text(encoding="utf-8").strip() == signature and all(
            path.is_file() for path in (cecil, helper, patcher, verifier)):
        return tools
    if not compiler().is_file():
        raise InstallerError("The built-in .NET Framework compiler is missing. Enable/repair Windows .NET Framework 4.x, then rerun.")
    with zipfile.ZipFile(work / ".tools" / "cecil.zip") as archive:
        cecil_bytes = archive.read("lib/net40/Mono.Cecil.dll")
    if hashlib.sha256(cecil_bytes).hexdigest().upper() != CECIL_DLL_SHA256:
        raise InstallerError("Bundled Mono.Cecil assembly failed its integrity check.")
    cecil.write_bytes(cecil_bytes)
    for path in (helper, patcher, verifier):
        if path.exists():
            path.unlink()
    print("Building the single-player patcher from the bundled sources...", flush=True)
    run_process([compiler(), "/nologo", "/target:library", "/platform:anycpu", "/optimize+",
                 f"/out:{helper}", str(source_dir / "TldStable.cs")], tools, log, "Single-player helper compilation")
    shared = [str(source_dir / name) for name in ("Checks.cs", "Expected.cs", "Invariants.cs")]
    run_process([compiler(), "/nologo", "/target:exe", "/platform:anycpu", "/optimize+", f"/out:{patcher}",
                 f"/reference:{cecil}", f"/resource:{helper},TldStableHelper.dll", *shared,
                 str(source_dir / "PatchV4.cs")], tools, log, "PatchV4 compilation")
    run_process([compiler(), "/nologo", "/target:exe", "/platform:anycpu", "/optimize+", f"/out:{verifier}",
                 f"/reference:{cecil}", *shared, str(source_dir / "VerifyV4.cs")], tools, log, "VerifyV4 compilation")
    if not all(path.is_file() for path in (cecil, helper, patcher, verifier)):
        raise InstallerError("The single-player tools were not produced by the bundled compiler.")
    marker.write_text(signature + "\n", encoding="utf-8")
    return tools


def stage_dir(work: Path, kind: str) -> Path:
    return work / kind / (time.strftime("%Y%m%d-%H%M%S") + "-" + str(os.getpid()))


def build_singleplayer(v3_file: Path, baseline: str, managed: Path, work: Path, log):
    """Patch a copy of a multiplayer v3 assembly with the v4 pass and verify it."""
    tools = ensure_singleplayer_tools(work, log)
    stage = stage_dir(work, "v4-stage")
    stage.mkdir(parents=True, exist_ok=True)
    source = stage / "Assembly-CSharp.v3.dll"
    output = stage / "Assembly-CSharp.v4.dll"
    shutil.copyfile(v3_file, source)
    if sha256(source) != baseline:
        raise InstallerError("The multiplayer assembly changed while copying. Nothing was installed.")
    print("Applying the single-player pass to a copy...", flush=True)
    run_process([tools / "PatchV4.exe", source, output, managed, baseline], stage, log, "PatchV4")
    print("Verifying the patched copy...", flush=True)
    run_process([tools / "VerifyV4.exe", source, output, baseline], stage, log, "VerifyV4")
    if sha256(output) == baseline:
        raise InstallerError("The single-player pass produced an unchanged assembly.")
    edits = read_json(stage / "v4-receipt.json").get("edits")
    if not isinstance(edits, list) or not edits:
        raise InstallerError("The single-player pass did not report its edits.")
    return output, edits


def build_multiplayer(work: Path, log, game: Path) -> Path:
    """Build and verify v3 from the embedded sources; returns its manifest."""
    output = stage_dir(work, "v3-build")
    output.parent.mkdir(parents=True, exist_ok=True)
    print("Building the patch from source for this game...", flush=True)
    run_ps(work, log, "Build-Patch.ps1", game, "-OutputDirectory", str(output))
    return output / "manifest.json"


def apply_singleplayer(game: Path, work: Path, log, prepared=None) -> str:
    """Apply v4 to a copy of the installed multiplayer assembly, verify, then swap.
    prepared supplies the output, edits, verified hash and target v3 baseline."""
    managed = managed_dir(game)
    assembly = game_assembly(game)
    v3 = verified_v3(game)
    baseline = receipt_hash(v3, "patchedSha256")
    runtime = receipt_hash(v3, "runtimeSha256")
    if sha256(assembly) != baseline:
        raise InstallerError("The installed multiplayer assembly does not match tldmp-v3-receipt.json. Restore and reinstall the multiplayer patch.")
    if prepared is not None:
        # A verified candidate built earlier: refuse to install it if the file
        # changed since verification or it targets a different v3 baseline.
        output = prepared["output"]
        edits = prepared["edits"]
        if not output.is_file() or not isinstance(edits, list) or not edits:
            raise InstallerError("The prepared single-player candidate is missing.")
        if sha256(output) != prepared["sha256"]:
            raise InstallerError("The prepared single-player candidate changed after verification.")
        if prepared["baseline"] != baseline:
            raise InstallerError("The prepared single-player candidate does not match the installed multiplayer build.")
    else:
        output, edits = build_singleplayer(assembly, baseline, managed, work, log)
    patched = sha256(output)
    backup = managed / V4_BACKUP
    if backup.is_file():
        if sha256(backup) != baseline:
            raise InstallerError("An existing single-player backup is not the installed multiplayer build.")
    else:
        stage_replace(assembly, backup, baseline, ".v4backup")
    stage_replace(output, assembly, patched, ".v4new")
    write_json(managed / V4_RECEIPT, {
        "version": 4,
        "patch": "single-player",
        "createdUtc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "input": {"file": "Assembly-CSharp.dll (multiplayer v3)", "sha256": baseline},
        "output": {"file": "Assembly-CSharp.dll", "sha256": patched, "bytes": output.stat().st_size},
        "originalSha256": baseline,
        "patchedSha256": patched,
        "runtimeSha256": runtime,
        "backup": V4_BACKUP,
        "verify": "PASS",
        "edits": edits,
    })
    return patched


def restore_singleplayer(game: Path, log) -> str:
    """Swap the verified v4 backup back in and remove the v4 receipt."""
    managed = managed_dir(game)
    assembly = game_assembly(game)
    receipt = read_json(managed / V4_RECEIPT)
    if receipt.get("version") != 4:
        raise InstallerError("tldmp-v4-receipt.json is not a recognised single-player receipt.")
    patched = receipt_hash(receipt, "patchedSha256")
    baseline = receipt_hash(receipt, "originalSha256")
    if not valid_hash(patched) or not valid_hash(baseline):
        raise InstallerError("The single-player receipt is missing its verified hashes.")
    if sha256(assembly) != patched:
        raise InstallerError("The installed assembly is not the build in tldmp-v4-receipt.json. Refusing to overwrite it.")
    v3 = verified_v3(game)
    if receipt_hash(v3, "patchedSha256") != baseline or receipt_hash(v3, "runtimeSha256") != receipt_hash(receipt, "runtimeSha256"):
        raise InstallerError("The multiplayer receipt no longer matches the single-player backup. Refusing.")
    backup = managed / V4_BACKUP
    if not backup.is_file():
        raise InstallerError("The single-player backup is missing. Verify the game files in Steam to recover.")
    if sha256(backup) != baseline:
        raise InstallerError("The single-player backup changed. Refusing to overwrite the installed assembly.")
    stage_replace(backup, assembly, baseline, ".v4restore")
    for path in (managed / V4_RECEIPT, backup):
        try:
            path.unlink()
        except OSError:
            pass
    print("Single-player pass removed; the verified multiplayer build is back.", flush=True)
    return baseline


def clear_singleplayer_files(game: Path) -> None:
    """Remove a leftover v4 receipt/backup once the multiplayer restore is done."""
    managed = managed_dir(game)
    receipt_path = managed / V4_RECEIPT
    backup = managed / V4_BACKUP
    try:
        receipt = read_json(receipt_path)
    except InstallerError:
        return
    if (receipt.get("version") == 4 and backup.is_file()
            and sha256(backup) == receipt_hash(receipt, "originalSha256")):
        for path in (receipt_path, backup):
            try:
                path.unlink()
            except OSError:
                pass


def clear_multiplayer_files(game: Path) -> None:
    """Remove the v3 receipt/backup once the original assembly is verified back."""
    assembly = game_assembly(game)
    if not assembly.is_file() or sha256(assembly) != ORIGINAL_SHA256:
        return
    managed = assembly.parent
    receipt_path = managed / "tldmp-v3-receipt.json"
    backup = managed / "Assembly-CSharp.tldmp-v3-original.bin"
    try:
        receipt = read_json(receipt_path)
    except InstallerError:
        return
    if receipt_hash(receipt, "originalSha256") != ORIGINAL_SHA256:
        return
    if not backup.is_file() or sha256(backup) != ORIGINAL_SHA256:
        return
    for path in (receipt_path, backup):
        try:
            path.unlink()
        except OSError:
            pass


def restore_multiplayer(work: Path, log, state: str, game: Path) -> None:
    script = {"v3": "Manage-Stability.ps1", "v1": "Manage-Patch.ps1"}[state]
    run_ps(work, log, script, game, "-Action", "Restore")
    clear_singleplayer_files(game)
    clear_multiplayer_files(game)


def snapshot_managed(game: Path, cache: Path) -> Path:
    """Keep the verified installed chain so a failed update can be recovered
    by hand. Copies only known patch files plus a hash manifest, never saves."""
    managed = managed_dir(game)
    folder = Path(tempfile.mkdtemp(prefix="rollback-", dir=cache))
    manifest = {}
    for name in ("Assembly-CSharp.dll", "Tld.Multiplayer.dll", "tldmp-v1-receipt.json", "tldmp-v3-receipt.json",
                 "tldmp-v4-receipt.json", "Assembly-CSharp.tldmp-v1-original.bin",
                 "Assembly-CSharp.tldmp-v3-original.bin", V4_BACKUP):
        source = managed / name
        if source.is_file():
            shutil.copyfile(source, folder / name)
            manifest[name] = sha256(folder / name)
    write_json(folder / "MANIFEST.json", {"createdUtc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                                        "game": str(game), "files": manifest})
    return folder


def main_cli(argv=None, progress=None) -> int:
    def emit(percent: int, phase: str) -> None:
        if progress is not None:
            try:
                progress(percent, phase)
            except Exception:
                pass
        print(f"[{percent:>3}%] {phase}", flush=True)

    parser = argparse.ArgumentParser(description=f"{APP_TITLE} installer (multiplayer + single-player). No arguments opens the GUI.")
    parser.add_argument("--game-dir", help="Override Steam game detection")
    action = parser.add_mutually_exclusive_group()
    action.add_argument("--restore", action="store_true", help="Undo the newest pass only (v4 -> v3, or v3 -> vanilla)")
    action.add_argument("--restore-all", action="store_true", help="Undo every pass (v4 -> v3 -> vanilla)")
    action.add_argument("--test-only", action="store_true", help="Build and verify the patch without changing the game")
    action.add_argument("--status", action="store_true", help="Inspect installation without changing files")
    action.add_argument("--check-updates", action="store_true", help="Check GitHub for a newer published release (read-only)")
    action.add_argument("--list", action="store_true", help="List detected Steam installations")
    action.add_argument("--update", action="store_true", help="Update an older recognized install to this bundled build")
    parser.add_argument("--allow-downgrade", action="store_true", help="Permit replacing a newer recognized Roadworthy release")
    parser.add_argument("--no-pause", action="store_true", help="Exit without waiting for Enter")
    parser.add_argument("--cache-dir", help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        if os.name != "nt":
            raise InstallerError("This patch installer is for Windows x64.")
        print(f"{APP_TITLE} v{VERSION} - multiplayer + single-player", flush=True)
        print("The host and every joining player must use this same patch build.", flush=True)
        if args.list:
            for game in discover_games():
                print(game)
            return 0
        if args.check_updates:
            result = check_updates()
            if result["version"] is None:
                print(f"Bundled release: {VERSION}\nNo published releases found.")
            else:
                print(f"Bundled release: {VERSION}\nLatest published: {result['tag']} "
                      f"({'newer' if result['newer'] else 'not newer'}; prereleases included)")
                if result["newer"]:
                    print(result["url"])
            return 0
        game = choose_game(args.game_dir)
        emit(0, "Checking the current installation")
        state = installed_state(game)
        info = installation_info(game)
        shown_build = (info.get("build") or info.get("sourceSignature") or "unknown")[:12]
        print(f"Game: {game}\nCurrent installation: {state} (release {info['version'] or 'unknown'}, build {shown_build})\nBundled release: {VERSION} (payload {PAYLOAD_SHA256[:12]})", flush=True)
        if args.status:
            emit(100, "Inspection complete")
            return 0
        restoring = args.restore or args.restore_all
        if restoring and state == "original":
            print("Original game already installed."); emit(100, "Nothing to restore"); return 0
        if not restoring and not args.test_only:
            if info["relation"] == "current":
                print("This bundled build is already installed (multiplayer v3 + single-player v4).")
                emit(100, "Already up to date"); return 0
            if info["relation"] == "newer" and not args.allow_downgrade:
                raise InstallerError(f"A newer Roadworthy release ({info['version']}) is installed. It will not be replaced automatically; rerun with --allow-downgrade only if you mean it.")
        preflight(game, need_compiler=not restoring)
        emit(5, "Preflight checks complete")
        cache = Path(args.cache_dir).expanduser().resolve() if args.cache_dir else Path(os.environ.get("LOCALAPPDATA", str(Path.home() / "AppData" / "Local"))) / "TheLongDrive-Roadworthy"
        work = cache / ("src-" + PAYLOAD_SHA256[:16].lower())
        with installer_lock(cache):
            extract_payload(work)
            emit(10, "Bundled sources extracted")
            logs = cache / "logs"
            logs.mkdir(parents=True, exist_ok=True)
            log_path = logs / (time.strftime("%Y%m%d-%H%M%S") + f"-{os.getpid()}.log")
            print(f"Sources and builds: {work}\nLog: {log_path}", flush=True)
            with log_path.open("w", encoding="utf-8") as log:
                # The lock is held: re-validate before trusting earlier reads.
                state = installed_state(game)
                info = installation_info(game)
                if not restoring and not args.test_only and info["relation"] == "newer" and not args.allow_downgrade:
                    raise InstallerError("A newer Roadworthy release is installed; refusing to downgrade.")
                if restoring:
                    # --restore of v4 removes the newest pass only; every other
                    # --restore (and always --restore-all) returns to vanilla.
                    entered = state
                    if entered == "v4":
                        restore_singleplayer(game, log)
                        state = "v3"
                        emit(55, "Single-player pass removed")
                    else:
                        emit(55, "No single-player pass present")
                    want_vanilla = args.restore_all or entered != "v4"
                    if want_vanilla and state in ("v1", "v3"):
                        restore_multiplayer(work, log, state, game)
                        state = "original"
                        emit(90, "Multiplayer patch removed")
                        print("Original game restored. Saves unchanged.")
                    else:
                        emit(90, "Multiplayer patch kept" if state != "original" else "Original game already installed")
                    expected = "original" if want_vanilla else "v3"
                    if installed_state(game) != expected:
                        raise InstallerError(f"Restore finished in the '{installed_state(game)}' state instead of '{expected}'.")
                    emit(100, "Verified installation restored")
                elif args.test_only:
                    manifest = read_json(build_multiplayer(work, log, game))
                    emit(40, "v3 candidate built and verified")
                    build_singleplayer(Path(manifest["patched"]), manifest["patchedSha256"].upper(), managed_dir(game), work, log)
                    emit(90, "v4 candidate built and verified")
                    emit(100, "All build and verification checks passed")
                    print("Build and verification passed. The game installation and saves were not changed.")
                else:
                    # Verify both candidates before anything touches the old chain.
                    manifest = build_multiplayer(work, log, game)
                    manifest_data = read_json(manifest)
                    candidate_v3 = Path(manifest_data["patched"])
                    candidate_v3_hash = sha256(candidate_v3)
                    candidate_runtime = Path(manifest_data["runtime"])
                    baseline_v3 = manifest_data.get("patchedSha256", "")
                    runtime_hash = manifest_data.get("runtimeSha256", "")
                    if (not isinstance(baseline_v3, str) or baseline_v3.upper() != candidate_v3_hash
                            or not valid_hash(runtime_hash) or sha256(candidate_runtime) != runtime_hash.upper()
                            or manifest_data.get("originalSha256") != ORIGINAL_SHA256):
                        raise InstallerError("The v3 build manifest failed its integrity check.")
                    emit(40, "v3 candidate built and verified")
                    managed = managed_dir(game)
                    v4_output, v4_edits = build_singleplayer(candidate_v3, baseline_v3.upper(), managed, work, log)
                    prepared_v4 = {"output": v4_output, "edits": v4_edits,
                                   "sha256": sha256(v4_output), "baseline": baseline_v3.upper()}
                    emit(65, "v4 candidate built and verified")
                    # Freeze: the staged candidates must be byte-identical to
                    # what the verifiers saw before the first restore runs.
                    if (sha256(candidate_v3) != candidate_v3_hash
                            or sha256(candidate_runtime) != runtime_hash.upper()
                            or sha256(v4_output) != prepared_v4["sha256"]):
                        raise InstallerError("A verified candidate changed on disk. Refusing to touch the installed chain.")
                    state = installed_state(game)
                    info = installation_info(game)
                    if info["relation"] == "newer" and not args.allow_downgrade:
                        raise InstallerError("A newer Roadworthy release is installed; refusing to downgrade.")
                    rollback = snapshot_managed(game, cache)
                    print(f"Recovery copies of the previous chain: {rollback}", flush=True)
                    preflight(game, need_compiler=False)
                    # Manage-Stability Install only replaces the original
                    # assembly, so unwind the old patch to vanilla first.
                    if state == "v4":
                        restore_singleplayer(game, log)
                        state = "v3"
                    if state in ("v1", "v3"):
                        restore_multiplayer(work, log, state, game)
                        state = "original"
                    emit(70, "Previous patch restored to the original game" if state == "original" else "Original game already installed")
                    run_ps(work, log, "Manage-Stability.ps1", game, "-Action", "Install", "-ManifestPath", str(manifest))
                    emit(85, "Candidate multiplayer build installed")
                    apply_singleplayer(game, work, log, prepared=prepared_v4)
                    emit(95, "Candidate single-player pass installed")
                    if installed_state(game) != "v4":
                        raise InstallerError("Post-install verification did not find the installed v4 chain.")
                    stamp_metadata(managed / "tldmp-v3-receipt.json")
                    stamp_metadata(managed / V4_RECEIPT)
                    emit(100, "Installed chain verified and stamped")
                    print("Done. Multiplayer v3 and the single-player pass are installed with verified backups. Saves unchanged.")
        return 0
    except (InstallerError, OSError, ValueError, zipfile.BadZipFile) as exc:
        print(f"\nStopped: {exc}", file=sys.stderr, flush=True)
        return 1
    finally:
        if not args.no_pause and sys.stdin is not None and sys.stdin.isatty():
            try:
                input("\nPress Enter to close...")
            except (EOFError, KeyboardInterrupt):
                pass


