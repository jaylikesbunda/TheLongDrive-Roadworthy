using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Mono.Cecil;
using TldMp;

// Generates stand-ins for the stable branch's game types that the beta deleted, so TLDLoader mods
// built for stable can still name them: fields with the same names and (beta-mapped) types,
// constructors that copy matching arguments into fields, and methods that do nothing and return
// the default. Only signatures are taken from the stable assembly, never code.
// Stable MonoBehaviours stay MonoBehaviours: mods compare them with Unity's null check.
// args: <stable Assembly-CSharp> <beta Assembly-CSharp> <beta Managed dir> <out shells .cs> <out names .cs>
internal static class TldStableShellGen
{
    static HashSet<string> betaTypes, shellNames;
    static HashSet<string> managedAssemblies;
    static readonly HashSet<string> keywords = new HashSet<string> { "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const", "continue", "decimal",
        "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int",
        "interface", "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override", "params", "private", "protected", "public", "readonly", "ref",
        "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
        "unsafe", "ushort", "using", "virtual", "void", "volatile", "while" };
    static readonly HashSet<string> unityMessages = new HashSet<string> { "Awake", "Start", "Update", "FixedUpdate", "LateUpdate", "OnEnable", "OnDisable", "OnDestroy", "OnGUI",
        "OnTriggerEnter", "OnTriggerExit", "OnTriggerStay", "OnCollisionEnter", "OnCollisionExit", "OnCollisionStay", "OnApplicationQuit", "OnValidate", "Reset", "OnDrawGizmos" };

    public static int Main(string[] args)
    {
        var stable = ModuleDefinition.ReadModule(args[0]);
        var beta = ModuleDefinition.ReadModule(args[1]);
        managedAssemblies = new HashSet<string>(Directory.GetFiles(args[2], "*.dll").Select(Path.GetFileNameWithoutExtension), StringComparer.OrdinalIgnoreCase);
        betaTypes = new HashSet<string>(beta.GetTypes().Select(t => t.FullName));
        var shells = stable.GetTypes().Where(t => !t.Name.StartsWith("<") && !betaTypes.Contains(t.FullName) && !t.IsInterface &&
            (TldLoaderCompatPolicy.RenamedType(t.FullName) == null || TldLoaderCompatPolicy.RenamedToRuntime(TldLoaderCompatPolicy.RenamedType(t.FullName)))).ToList();
        shellNames = new HashSet<string>(shells.Select(t => t.FullName));

        var code = new StringBuilder();
        code.AppendLine("// <auto-generated> by tools/TldStableShellGen.cs from the stable and beta Assembly-CSharp signatures. Do not edit.");
        code.AppendLine("// Stand-ins for stable game types the beta deleted (see TldLoaderCompatPolicy.RenamedType).");
        code.AppendLine("#pragma warning disable 0649, 0169, 0414, 0108, 0114");
        code.AppendLine("namespace TldMp.StableShells");
        code.AppendLine("{");
        // These audio APIs have implementations in TldLoaderCompat.cs.
        foreach (var type in shells.Where(t => t.FullName != "WAV" && t.FullName != "NAudioPlayer").OrderBy(t => t.FullName, StringComparer.Ordinal))
            Emit(code, type);
        code.AppendLine("}");
        File.WriteAllText(args[3], code.ToString());

        var names = new StringBuilder();
        names.AppendLine("// <auto-generated> by tools/TldStableShellGen.cs. Do not edit.");
        names.AppendLine("namespace TldMp");
        names.AppendLine("{");
        names.AppendLine("    // Stable game types the beta deleted; mods' references go to TldMp.StableShells (TldStableShells.cs).");
        names.AppendLine("    internal static class TldStableShellNames");
        names.AppendLine("    {");
        names.AppendLine("        internal static readonly string[] All =");
        names.AppendLine("        {");
        foreach (string name in shellNames.OrderBy(n => n, StringComparer.Ordinal)) names.AppendLine("            \"" + name + "\",");
        names.AppendLine("        };");
        names.AppendLine("    }");
        names.AppendLine("}");
        File.WriteAllText(args[4], names.ToString());
        Console.WriteLine("Generated " + shells.Count + " stand-in types.");
        return 0;
    }

    static string Flat(string fullName) { return fullName.Replace('/', '_'); }

    static void Emit(StringBuilder code, TypeDefinition type)
    {
        string name = Flat(type.FullName);
        if (type.IsEnum)
        {
            var underlying = type.Fields.First(f => !f.IsStatic).FieldType;
            code.AppendLine("    public enum " + name + " : " + Map(underlying));
            code.AppendLine("    {");
            foreach (var f in type.Fields.Where(f => f.IsStatic && f.HasConstant)) code.AppendLine("        " + Id(f.Name) + " = " + Convert.ToInt64(f.Constant) + ",");
            code.AppendLine("    }");
            return;
        }
        bool behaviour = IsBehaviour(type);
        string kind = type.IsValueType ? "struct" : "class";
        code.AppendLine("    public " + (name == "save_prefab" ? "partial " : "") + kind + " " + name + (behaviour ? " : global::UnityEngine.MonoBehaviour" : ""));
        code.AppendLine("    {");
        var fieldNames = new HashSet<string>();
        foreach (var field in type.Fields.Where(f => !f.Name.Contains("<") && !f.HasConstant))
        {
            if (field.IsStatic && type.IsValueType && field.FieldType.FullName == type.FullName) continue;
            code.AppendLine("        public " + (field.IsStatic ? "static " : "") + Map(field.FieldType) + " " + Id(field.Name) + ";");
            fieldNames.Add(field.Name);
        }
        var signatures = new HashSet<string>();
        if (!behaviour)
        {
            if (!type.IsValueType) { code.AppendLine("        public " + name + "() { }"); signatures.Add(".ctor()"); }
            foreach (var ctor in type.Methods.Where(m => m.IsConstructor && !m.IsStatic && m.HasParameters))
            {
                // The save adapter implements the constructor's coordinate conversion.
                if (name == "save_prefab" && ctor.Parameters.Count == 8) continue;
                var parameters = ctor.Parameters.Select(p => Map(p.ParameterType)).ToArray();
                if (parameters.Any(p => p.Contains("&"))) continue;
                string sig = ".ctor(" + string.Join(",", parameters) + ")";
                if (!signatures.Add(sig)) continue;
                var body = new StringBuilder();
                if (type.IsValueType) body.Append("this = default(" + name + "); ");
                for (int i = 0; i < ctor.Parameters.Count; i++)
                {
                    var match = fieldNames.FirstOrDefault(f => string.Equals(f, ctor.Parameters[i].Name, StringComparison.OrdinalIgnoreCase) && type.Fields.First(x => x.Name == f).FieldType.FullName == ctor.Parameters[i].ParameterType.FullName && !type.Fields.First(x => x.Name == f).IsStatic);
                    if (match != null) body.Append("this." + Id(match) + " = " + Id(Param(ctor.Parameters[i], i)) + "; ");
                }
                code.AppendLine("        public " + name + "(" + string.Join(", ", ctor.Parameters.Select((p, i) => Map(p.ParameterType) + " " + Id(Param(p, i))).ToArray()) + ") { " + body + "}");
            }
        }
        foreach (var method in type.Methods.Where(m => !m.IsConstructor && !m.IsSpecialName && !m.HasGenericParameters && !m.Name.Contains("<") && !m.Name.Contains(".")))
        {
            if (behaviour && unityMessages.Contains(method.Name)) continue;
            if (fieldNames.Contains(method.Name)) continue;
            var parameters = method.Parameters.Select(p => (p.ParameterType.IsByReference ? (p.IsOut ? "out " : "ref ") : "") + Map(p.ParameterType is ByReferenceType ? ((ByReferenceType)p.ParameterType).ElementType : p.ParameterType)).ToArray();
            string sig = (method.IsStatic ? "static " : "") + method.Name + "(" + string.Join(",", parameters) + ")";
            if (!signatures.Add(method.Name + "(" + string.Join(",", parameters) + ")")) continue;
            string ret = Map(method.ReturnType);
            var body = new StringBuilder();
            for (int i = 0; i < method.Parameters.Count; i++) if (method.Parameters[i].IsOut) body.Append(Id(Param(method.Parameters[i], i)) + " = default(" + Map(((ByReferenceType)method.Parameters[i].ParameterType).ElementType) + "); ");
            body.Append("global::TldMp.TldLoaderBridge.MissingCall(\"" + type.FullName + "::" + method.Name + "\"); ");
            if (ret != "void") body.Append("return default(" + ret + "); ");
            code.AppendLine("        public " + (method.IsStatic ? "static " : "") + ret + " " + Id(method.Name) + "(" +
                string.Join(", ", method.Parameters.Select((p, i) => parameters[i] + " " + Id(Param(p, i))).ToArray()) + ") { " + body + "}");
        }
        code.AppendLine("    }");
    }

    static string Param(ParameterDefinition p, int index) { return string.IsNullOrEmpty(p.Name) ? "a" + index : p.Name; }

    static bool IsBehaviour(TypeDefinition type)
    {
        for (var b = type.BaseType; b != null; )
        {
            if (b.FullName == "UnityEngine.MonoBehaviour" || b.FullName == "UnityEngine.Component" || b.FullName == "UnityEngine.Behaviour") return true;
            TypeDefinition d;
            try { d = b.Resolve(); } catch (Exception) { return false; }
            if (d == null) return false;
            b = d.BaseType;
        }
        return false;
    }

    static string Id(string name) { return keywords.Contains(name) ? "@" + name : name; }

    // A stable type as the stand-ins name it: beta game type, renamed type, another stand-in,
    // or the Unity/.NET type itself; anything from an assembly the beta lacks becomes object.
    static string Map(TypeReference type)
    {
        if (type is GenericParameter) return "object";
        var array = type as ArrayType;
        if (array != null) return Map(array.ElementType) + "[" + new string(',', array.Rank - 1) + "]";
        var instance = type as GenericInstanceType;
        if (instance != null)
        {
            string element = Map(instance.ElementType);
            if (element == "object") return "object";
            int tick = element.IndexOf('`');
            if (tick >= 0) element = element.Substring(0, tick);
            return element + "<" + string.Join(", ", instance.GenericArguments.Select(Map).ToArray()) + ">";
        }
        switch (type.FullName)
        {
            case "System.Void": return "void";
            case "System.Boolean": return "bool";
            case "System.Byte": return "byte";
            case "System.SByte": return "sbyte";
            case "System.Int16": return "short";
            case "System.UInt16": return "ushort";
            case "System.Int32": return "int";
            case "System.UInt32": return "uint";
            case "System.Int64": return "long";
            case "System.UInt64": return "ulong";
            case "System.Single": return "float";
            case "System.Double": return "double";
            case "System.String": return "string";
            case "System.Char": return "char";
            case "System.Object": return "object";
        }
        // A type defined in the same assembly reports the module ("Assembly-CSharp.dll") as its scope.
        string scope = type.Scope is ModuleDefinition ? "Assembly-CSharp" : type.Scope == null ? "" : type.Scope.Name;
        if (scope == "Assembly-CSharp")
        {
            string renamed = TldLoaderCompatPolicy.RenamedType(type.FullName);
            if (renamed != null)
                return renamed == "System.Object" ? "object" : "global::" + TldLoaderCompatPolicy.WithoutAssembly(renamed).Replace('/', '.');
            if (shellNames.Contains(type.FullName)) return "global::TldMp.StableShells." + Flat(type.FullName);
            if (betaTypes.Contains(type.FullName)) return "global::" + type.FullName.Replace('/', '.');
            return "object";
        }
        if (scope == "mscorlib" || scope == "netstandard" || scope == "System" || scope == "System.Core" || managedAssemblies.Contains(scope))
        {
            string full = type.FullName.Replace('/', '.');
            int tick = full.IndexOf('`');
            if (tick >= 0) full = full.Substring(0, tick);
            return "global::" + full;
        }
        return "object";
    }
}
